"""Score the live agent against the golden set (evals/golden.jsonl, built by evals/golden.py).

  uv run python -m evals.golden_run                 # all cases, writes ../docs/golden_report.md
  uv run python -m evals.golden_run --only wrench   # cases whose id starts with a prefix
  uv run python -m evals.golden_run --no-judge      # skip the LLM-as-judge pass (deterministic checks only)

Per case:  pass/fail, precision (mentioned products that are correct or acceptable context),
           recall (must_include found), forbidden products mentioned, invented model numbers.
Exit code 1 if any case fails.
"""

import argparse
import csv
import json
import re
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from app.core.config import settings
from app.services.agent import Session, run_turn
from evals.judge import DIMENSIONS, calibrate, judge

HERE = Path(__file__).resolve().parent
GOLDEN = HERE / "golden.jsonl"
REPORT = HERE.parents[1] / "docs" / "golden_report.md"
DATA = HERE.parent / "data" / "bosch_product_catalog_mock.csv"

TOKEN = re.compile(r"[A-Za-z0-9][A-Za-z0-9-]*[A-Za-z0-9]")
MODEL_LIKE = re.compile(r"^(?=.*\d)(?=.*[A-Z])[A-Z0-9]+(?:-[A-Z0-9]+)*$")
ASKS = re.compile(r"\?|\b(which|please (tell|provide|share|specify|let)|let me know)\b", re.IGNORECASE)

_rows = list(csv.DictReader(DATA.open(encoding="utf-8")))
MODELS = {r["model_number"] for r in _rows}
# every token that appears anywhere in the catalog: a model-like token outside this set was invented
VOCAB = {t for r in _rows for v in r.values() for t in TOKEN.findall(v)}


def mentioned(text: str, numeric: bool) -> list[str]:
    out = []
    for t in TOKEN.findall(text):
        if t in MODELS and (numeric or not t.isdigit()) and t not in out:
            out.append(t)
    return out


def invented(text: str, question: str) -> list[str]:
    asked = set(TOKEN.findall(question))
    return sorted({t for t in TOKEN.findall(text) if len(t) >= 5 and MODEL_LIKE.match(t) and t not in VOCAB and t not in asked})


def score(c: dict) -> dict:
    session, text, tools, errors = Session(), [], [], []
    t0 = time.perf_counter()
    for ev in run_turn(session, c["question"]):
        if ev["type"] == "token":
            text.append(ev["text"])
        elif ev["type"] == "tool_call":
            tools.append(ev["name"])
        elif ev["type"] == "error":
            errors.append(ev["message"])
    reply = "".join(text)
    low = reply.lower()

    seen = mentioned(reply, c["numeric_models"])
    allowed = set(c["acceptable"]) | set(c["context_ok"]) | set(c["must_include"]) | set(TOKEN.findall(c["question"]))
    missing = [m for m in c["must_include"] if m not in seen]
    hits_acceptable = [m for m in seen if m in c["acceptable"]]
    forbidden = [m for m in seen if m in c["forbidden"]]
    made_up = invented(reply, c["question"])
    text_missing = [g for g in c["any_text"] if not any(p.lower() in low for p in g)]

    failures = [f"error: {e}" for e in errors]
    if c["expect"] == "clarify":
        if tools or not ASKS.search(reply):
            failures.append("expected a clarifying question without tool calls")
    else:
        failures += [f"missing {m}" for m in missing]
        if len(hits_acceptable) < c["min_acceptable"]:
            failures.append(f"only {len(hits_acceptable)} correct products, need {c['min_acceptable']}")
        failures += [f"text: none of {g[:3]}…" for g in text_missing]
    failures += [f"forbidden {m}" for m in forbidden]
    failures += [f"invented {m}" for m in made_up]

    graded = c["expect"] == "answer" and (c["acceptable"] or c["must_include"])
    return {
        "case": c, "passed": not failures, "failures": failures, "reply": reply, "tools": tools,
        "seconds": round(time.perf_counter() - t0, 1),
        "precision": (len([m for m in seen if m in allowed]) / len(seen)) if graded and seen else None,
        "recall": (1 - len(missing) / len(c["must_include"])) if c["must_include"] else None,
        "forbidden": forbidden, "invented": made_up,
    }


def mean(xs):
    xs = [x for x in xs if x is not None]
    return sum(xs) / len(xs) if xs else None


def pct(x):
    return "n/a" if x is None else f"{x:.0%}"


def report(results: list[dict], calib: list[dict]) -> str:
    cats: dict[str, list] = {}
    for r in results:
        cats.setdefault(r["case"]["category"], []).append(r)
    passed = sum(r["passed"] for r in results)
    lines = [
        "# Golden set report",
        "",
        "Generated by `uv run python -m evals.golden_run` against the live model. Expected answers come from",
        "`evals/golden.jsonl`, built from the raw CSV by `evals/golden.py` (independent of the agent's tools).",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Cases passed | **{passed}/{len(results)}** ({passed / len(results):.0%}) |",
        f"| Precision (mentioned products that are correct) | {pct(mean(r['precision'] for r in results))} |",
        f"| Recall (required products found) | {pct(mean(r['recall'] for r in results))} |",
        f"| Forbidden products mentioned | {sum(len(r['forbidden']) for r in results)} |",
        f"| Invented model numbers | {sum(len(r['invented']) for r in results)} |",
        f"| Avg tool calls / answer time | {mean(len(r['tools']) for r in results):.1f} / {mean(r['seconds'] for r in results):.1f}s |",
        "",
        "| Category | Passed | Precision | Recall |",
        "|---|---|---|---|",
    ]
    for cat, rs in cats.items():
        lines.append(f"| {cat} | {sum(r['passed'] for r in rs)}/{len(rs)} | {pct(mean(r['precision'] for r in rs))} | {pct(mean(r['recall'] for r in rs))} |")
    judged = [r for r in results if r.get("judge")]
    if judged:
        lines += ["", "## LLM-as-judge", "",
                  f"Judge model `{settings.judge_model}`, temperature 0, graded against catalog records from the CSV.", ""]
        if calib:
            ok = all(c["ok"] for c in calib)
            lines += [f"Calibration: **{sum(c['ok'] for c in calib)}/{len(calib)}** known-verdict probes graded correctly"
                      + ("" if ok else " ⚠️ judge missed a planted error, so treat its scores with caution"), "",
                      "| Probe | Expected | Judge |", "|---|---|---|",
                      *[f"| {c['probe']} | {c['expected']} | {c['got']} |" for c in calib], ""]
        lines += [f"Judge verdict pass: **{sum(r['judge']['verdict'] == 'pass' for r in judged)}/{len(judged)}**", "",
                  "| Dimension | Mean (1-5) |", "|---|---|",
                  *[f"| {d} | {mean(r['judge']['scores'][d]['score'] for r in judged):.2f} |" for d in DIMENSIONS]]
        disagree = [r for r in judged if (r["judge"]["verdict"] == "pass") != r["passed"]]
        lines += ["", "### Where the checks and the judge disagree", "" if disagree else "None."]
        for r in disagree:
            c = r["case"]
            lines += [f"- **{c['id']}**: checks {'pass' if r['passed'] else 'fail'}, judge {r['judge']['verdict']}: "
                      + "; ".join(r["judge"]["issues"] or [r["judge"]["scores"][d]["reason"] for d in ("correctness",)])]
        low = [r for r in judged if any(r["judge"]["scores"][d]["score"] <= 3 for d in DIMENSIONS)]
        lines += ["", "### Low scores (any dimension ≤ 3)", "" if low else "None."]
        for r in low:
            bad = {d: r["judge"]["scores"][d] for d in DIMENSIONS if r["judge"]["scores"][d]["score"] <= 3}
            lines += [f"- **{r['case']['id']}**: " + "; ".join(f"{d} {v['score']}: {v['reason']}" for d, v in bad.items())]
    fails = [r for r in results if not r["passed"]]
    lines += ["", "## Failures (deterministic checks)", "" if fails else "None."]
    for r in fails:
        c = r["case"]
        lines += [f"### {c['id']}: {c['question']}", f"- Expected: {c['source']}", *[f"- {f}" for f in r["failures"]],
                  f"- Tools: {', '.join(r['tools']) or 'none'}", "", "> " + r["reply"].replace("\n", "\n> "), ""]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", nargs="*", help="case id prefixes")
    ap.add_argument("--no-judge", action="store_true", help="skip the LLM-as-judge pass")
    args = ap.parse_args()
    cases = [json.loads(line) for line in GOLDEN.open()]
    all_cases = {c["id"]: c for c in cases}
    if args.only:
        cases = [c for c in cases if any(c["id"].startswith(p) for p in args.only)]

    with ThreadPoolExecutor(max_workers=8) as pool:
        results = list(pool.map(score, cases))
        calib = []
        if not args.no_judge:
            calib = calibrate(all_cases)
            for r, g in zip(results, pool.map(lambda r: judge(r["case"], r["reply"]), results), strict=True):
                r["judge"] = g

    for r in results:
        c = r["case"]
        jv = f" judge={r['judge']['verdict']}" if r.get("judge") else ""
        print(f"{'PASS' if r['passed'] else 'FAIL'} {c['id']:22} prec={pct(r['precision']):>4} rec={pct(r['recall']):>4}{jv}  {'; '.join(r['failures'])}")
    if not args.only:
        REPORT.write_text(report(results, calib))
        print(f"\nwrote {REPORT}")
    passed = sum(r["passed"] for r in results)
    print(f"\n{passed}/{len(results)} passed · precision {pct(mean(r['precision'] for r in results))} · "
          f"recall {pct(mean(r['recall'] for r in results))} · forbidden {sum(len(r['forbidden']) for r in results)} · "
          f"invented {sum(len(r['invented']) for r in results)}")
    if calib:
        print(f"judge calibration {sum(c['ok'] for c in calib)}/{len(calib)} · judge pass "
              f"{sum(r['judge']['verdict'] == 'pass' for r in results)}/{len(results)} · "
              + " · ".join(f"{d} {mean(r['judge']['scores'][d]['score'] for r in results):.2f}" for d in DIMENSIONS))
    return 0 if passed == len(results) else 1


if __name__ == "__main__":
    sys.exit(main())
